-- ============================================================================
-- 迁移 004：桌位名称调整
--
-- 门店叫法从「工位」改为「桌」，同步更新已有数据：
--   "01号工位" → "01号桌"
-- 表名与字段名保持不变（tables / table_sessions），避免无谓的结构变更。
-- ============================================================================

UPDATE tables
   SET name = REPLACE(name, '号工位', '号桌')
 WHERE name LIKE '%号工位%';

-- 已经开过台的记录里保存了桌名快照，一并同步，避免历史订单显示旧叫法
UPDATE orders
   SET table_name = REPLACE(table_name, '号工位', '号桌')
 WHERE table_name LIKE '%号工位%';
