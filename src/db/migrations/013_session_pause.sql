-- ============================================================================
-- 迁移 013：开台会话支持「暂停计时」
--
-- 【业务场景】
--   顾客中途要离开（出去吃饭、上厕所、接电话），店员可以暂停计时，
--   这段时间不计入使用时长。例如：
--     14:00 开台（1 小时套餐）
--     14:30 暂停，15:00 恢复
--   则实际计费时长 = 30 分钟 + 恢复后继续的时长，中间的 30 分钟不算。
--
-- 【实现方式：折算 started_at】
--   暂停时记录 paused_at；恢复时把暂停时长加到 started_at 与 expected_end_at 上，
--   让"开始时间"等效后移。这样 elapsedMinutes、超时计算、看板倒计时、结账
--   全部基于 started_at 的既有逻辑都自动正确，无需逐处修改。
--
--   暂停期间：paused_at 非空，看板与详情据此显示「已暂停」，倒计时冻结。
-- ============================================================================

ALTER TABLE table_sessions
  ADD COLUMN IF NOT EXISTS paused_at TIMESTAMPTZ;

COMMENT ON COLUMN table_sessions.paused_at IS
  '暂停计时的开始时间。NULL 表示未暂停。恢复时把暂停时长折算进 started_at 后清空';
