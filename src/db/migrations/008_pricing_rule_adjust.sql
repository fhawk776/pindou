-- ============================================================================
-- 迁移 008：按门店确认后的规则调整
--
-- 经与店主确认：
--   1. 加购项参与打折日的 8 折（原实现把加购排除在折扣之外）
--   2. 删除月卡（海报中没有该商品，属于早期误加）
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 加购项改为参与打折
-- ---------------------------------------------------------------------------
UPDATE products
   SET discountable = true
 WHERE category = 'addon';

-- 超时费仍然不参与折扣：它是惩罚性收费，不是商品。
-- （超时费不落 products 表，由 settings.pricing 控制，因此无需改动）

-- ---------------------------------------------------------------------------
-- 2. 下架月卡
--    不物理删除：已有订单可能引用它，删除会破坏历史记录的外键。
--    改为标记停用，既不出现在价目表，也保留历史可查。
-- ---------------------------------------------------------------------------
UPDATE products
   SET is_active = false
 WHERE card_type = 'month' OR code = 'MONTH';

COMMENT ON COLUMN products.discountable IS
  '是否参与打折日折扣；套餐、日卡、加购均为 true，周卡为 false';
